"""Единая подпись внутренней оценки сценария (этап 28D).

Баллы детектора — не эмпирическая вероятность успеха. Значения и
пороги остаются прежними, меняется только видимый пользователю текст.
"""
from __future__ import annotations

import config as cfg


def score_line(value: int | float) -> str:
    """Обратимо меняет подпись; не преобразует численное значение."""
    if getattr(cfg, "STAGE28D_SCENARIO_SCORE_WORDING", True):
        return f"Оценка сценария: {value}/100 · эвристика, не вероятность результата"
    return f"Вероятность: {value}%"
